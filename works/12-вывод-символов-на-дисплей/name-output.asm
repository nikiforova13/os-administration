; Практическая работа № 12.
; Циклический вывод строки "ОЛЯ ИЕВЛЕВА" на монитор КР580.
; Начальный адрес программы: 0000H.
;
; Порт монитора принимает два байта для каждого символа:
;   1) цвет 00H..7FH (старший бит 0 — текстовый режим);
;   2) код символа в CP866.

        MVI C, 01H     ; начальный цвет

REPT:   LXI H, NAME   ; HL указывает на первый символ
        MVI B, 0BH     ; длина строки — 11 символов

LOOP:   MOV A, C      ; передать цвет
        OUT 00H
        MOV A, M      ; передать CP866-код текущего символа
        OUT 00H

        INR C         ; следующий цвет
        MOV A, C
        ANI 7FH       ; оставить текстовый режим и диапазон 00H..7FH
        MOV C, A

        INX H         ; перейти к следующему символу
        DCR B         ; уменьшить число оставшихся символов
        JNZ LOOP
        JMP REPT      ; снова вывести имя и фамилию

; "ОЛЯ ИЕВЛЕВА" в кодировке CP866.
NAME:   DB 8EH, 8BH, 9FH, 20H, 88H, 85H
        DB 82H, 8BH, 85H, 82H, 80H
