; Практическая работа № 14.
; Сложение массива однобайтных беззнаковых чисел.
; Начальный адрес программы: 0000H.
;
; Младший байт суммы накапливается в A, старший — в C.
; При переносе из A команда INR C увеличивает старший байт.

        ORG 0000H

        LXI H, 0100H  ; HL указывает на первый элемент массива
        MVI B, 05H    ; B — количество элементов
        XRA A         ; A = 00H, флаг переноса сброшен
        MOV C, A      ; C = 00H — старший байт суммы

LOOP:   ADD M         ; A = A + [HL]
        JNC NEXT      ; если переноса нет, не изменять C
        INR C         ; учесть перенос в старшем байте

NEXT:   INX H         ; перейти к следующему элементу
        DCR B         ; уменьшить счётчик
        JNZ LOOP      ; продолжить, пока B не равен нулю

        LXI H, 0120H  ; адрес младшего байта результата
        MOV M, A      ; [0120H] = младший байт
        INX H         ; HL = 0121H
        MOV A, C
        MOV M, A      ; [0121H] = старший байт
        HLT           ; остановить процессор

        ORG 0100H
ARRAY:  DB 0A1H, 09BH, 0F0H, 080H, 040H

        ORG 0120H
RESULT: DB 00H, 00H
